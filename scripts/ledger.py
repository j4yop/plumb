"""The ledger, over one match or many.

Why this exists
---------------
The ledger is the artefact a club takes away: one row per claim, with the scope it is about and
the share of that scope the tracking can carry. On one match it is a curiosity. **Across ten
matches it becomes the product**, because the interesting sentence is not "this claim is
supported" but *"this claim is supported on seven of the ten, and the three where it is not are
the three where the feed lost the ball in that zone"*.

So this script is the same ledger, run over every match it is given, plus the aggregate: the
coverage of each claim across the set. That aggregate is what a collection plan is built from.

Usage
-----
::

    python3 scripts/ledger.py                      # the competition match
    python3 scripts/ledger.py --games 1,2,3        # Metrica's three sample matches
    python3 scripts/ledger.py --out artifacts/ledger.md

The claims are the committed ones — `plumb.facts.FACT_LIBRARY` — so the ledger cannot drift from
the tool.
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import Dict, List, Optional, Tuple

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from mtah.config import AWAY, DEAD, HOME, Config  # noqa: E402
from mtah.pipeline import decide  # noqa: E402

from plumb.analysis import Analysis  # noqa: E402
from plumb.facts import FACT_LIBRARY  # noqa: E402


def analysis_for(match, config: Config) -> Analysis:
    """Run the possession engine on any Match and hand back a claims-engine Analysis."""
    evidence, decision = decide(match, config)
    return Analysis(
        labels=decision.labels,
        spells=decision.spells,
        evidence=evidence,
        ball_xy=match.ball_xy,
        player_xy=match.player_xy,
        player_speed=match.player_speed,
        slot_team=match.slot_team,
        n_frames=match.n_frames,
        set_pieces=list(match.set_pieces),
        phases=list(match.phases),
        pitch_length_m=config.pitch_length_m,
        pitch_width_m=config.pitch_width_m,
        team_names=tuple(match.team_names),
        phase_windows={
            "first-half": config.first_half_frames,
            "second-half": config.second_half_frames,
            "halftime": config.half_time_frames,
        },
    )


def ledger_rows(analysis: Analysis) -> List[Tuple[str, str, str, float, str]]:
    """One row per claim: id, value, scope, coverage, status."""
    rows = []
    for fact_id, function in FACT_LIBRARY.items():
        try:
            fact = function(analysis, "all")
            rows.append((
                fact_id,
                " ".join(fact.answer.split()),
                fact.scope,
                fact.coverage_pct if fact.coverage_pct is not None else 0.0,
                fact.status,
            ))
        except Exception as error:  # one broken claim must not hide the rest
            rows.append((fact_id, "could not be computed: {}".format(error), "—", 0.0, "error"))
    return rows


def render(ledgers: Dict[str, List[Tuple[str, str, str, float, str]]],
           titles: Dict[str, str]) -> str:
    """The ledger, per match and then aggregated across the set."""
    names = sorted(ledgers)
    lines = [
        "# The ledger",
        "",
        "One row per claim, with the scope it is about and the share of that scope in which the",
        "ball was observed. Generated by `scripts/ledger.py` from the committed fact library.",
        "",
        "## The matches",
        "",
        "| match | claim | scope | coverage | status |",
        "|---|---|---|---:|---|",
    ]
    for name in names:
        for fact_id, value, scope, coverage, status in ledgers[name]:
            lines.append("| {} | `{}` | {} | {:.1f} % | {} |".format(
                titles.get(name, name), fact_id, scope, 100.0 * coverage, status))

    # The aggregate: the claim is only as good as its worst match.
    lines += [
        "",
        "## Across the set",
        "",
        "The row that matters for a collection plan is the last one: **the weakest match**, not the",
        "average. A claim that holds on nine matches and not on the tenth is a claim with a",
        "collection plan attached to it.",
        "",
        "| claim | matches supported | mean coverage | worst coverage | weakest match |",
        "|---|---:|---:|---:|---|",
    ]
    fact_ids = [row[0] for row in ledgers[names[0]]]
    for fact_id in fact_ids:
        values = []
        supported = 0
        for name in names:
            for row in ledgers[name]:
                if row[0] == fact_id:
                    values.append((name, row[3], row[4]))
                    if row[4] == "supported":
                        supported += 1
                    break
        applicable = [v for v in values if v[2] == "supported"]
        if not applicable:
            lines.append("| `{}` | 0 of {} | — | — | not applicable to this set |".format(
                fact_id, len(values)))
            continue
        coverages = [v[1] for v in applicable]
        worst = min(applicable, key=lambda v: v[1])
        lines.append("| `{}` | {} of {} | {:.1f} % | {:.1f} % | {} |".format(
            fact_id, supported, len(values),
            100.0 * float(np.mean(coverages)), 100.0 * worst[1],
            titles.get(worst[0], worst[0]),
        ))
    lines.append("")
    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="the ledger, over one match or many")
    parser.add_argument("--games", default=None,
                        help="comma-separated Metrica sample games, e.g. 1,2,3")
    parser.add_argument("--data-dir", default=None, help="the competition bundle")
    parser.add_argument("--out", default=None, help="write the ledger here")
    args = parser.parse_args(argv)

    ledgers: Dict[str, List[Tuple[str, str, str, float, str]]] = {}
    titles: Dict[str, str] = {}

    if args.games:
        import external_tuning as et

        base = Config()
        for token in args.games.split(","):
            game = int(token)
            try:
                match, _truth, config = et.load_game(game, base)
            except FileNotFoundError:
                print("game {}: not on this machine".format(game), file=sys.stderr)
                continue
            key = "game-{}".format(game)
            ledgers[key] = ledger_rows(analysis_for(match, config))
            titles[key] = "game {} ({} v {})".format(game, *match.team_names)
    else:
        from mtah.match import load_match

        config = Config(data_dir=args.data_dir or os.environ.get("MTAH_DATA_DIR", ""))
        match = load_match(config)
        ledgers["match"] = ledger_rows(analysis_for(match, config))
        titles["match"] = "{} v {}".format(*match.team_names)

    if not ledgers:
        print("no matches loaded", file=sys.stderr)
        return 1

    text = render(ledgers, titles)
    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        with open(args.out, "w") as handle:
            handle.write(text)
        print("wrote {} — {} claims over {} match(es)".format(
            args.out, len(next(iter(ledgers.values()))), len(ledgers)))
    else:
        print(text)

    # The number the pitch leads with: the weakest claim across the set.
    worst = min(
        ((row[0], row[3]) for rows in ledgers.values() for row in rows
         if row[4] == "supported"),
        key=lambda item: item[1],
        default=("—", 0.0),
    )
    print("weakest claim across the set: {} at {:.1f} % coverage".format(worst[0], 100 * worst[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
